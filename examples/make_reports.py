#!/usr/bin/env python3
"""Regenerate REPORT.md of every example below from the actual output of gatecost (run from anywhere).

(`mac/` has its own, richer `make_report.py`.)  Each example is a directory with a `baseline/` design and,
for most, a second variant against which `diff` is run.
"""
import os
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOL = HERE.parent / "scripts" / "gatecost"
CACHE = tempfile.mkdtemp(prefix="gatecost-examples-")   # never write a cache next to the sources

# (directory, top, variant directory or None, title, what it shows)
EXAMPLES = [
    ("counter_width", "counter", "wider", "enable counter, 8 -> 32 bits",
     "A parameter change: the cause is reported as the parameter, not as individual operators."),
    ("alu_multiplier", "alu", "with_mul", "16-bit ALU, one more operation (a multiplier)",
     "Adding a case arm that contains a multiplier; the contributor points at the new line."),
    ("fifo_depth", "fifo", "deeper", "register-array FIFO, depth 16 -> 64",
     "Memory-dominated designs: the confidence is `low` and the range is wide, but the verdict is `INCREASE`: the error of a resized memory cannot flip its sign (`DIFF.md` §9)."),
    ("fir_pipeline", "fir", "pipelined", "4-tap FIR, registering the products",
     "A pipeline stage costs flip-flops; the sum of the registered products is cheaper than the products' sum."),
    ("uart_tx", "uart_tx", None, "UART transmitter",
     "`bit` is a SystemVerilog keyword but a legal Verilog identifier: this file used to give a PARSE_ERROR."),
    ("sv_features", "top", None, "SystemVerilog constructs",
     "`$bits(port)` in a localparam, an array parameter of structs, `$error` in a generate, real-valued constants."),
    ("udp_mux", "mux4w", None, "user-defined primitive",
     "A combinational UDP is lowered from its truth table instead of being a zero-cost black box."),
    ("vhdl_fsm_alu", "alu", "wider", "VHDL registered ALU, generic 16 -> 32",
     "The same flow in VHDL, with a generic as the changed parameter."),
]


def run(cwd: Path, *args: str) -> str:
    env = dict(os.environ, GATECOST_CACHE_DIR=CACHE)
    p = subprocess.run([sys.executable, str(TOOL), *args], cwd=cwd, capture_output=True, text=True, env=env)
    return p.stdout.rstrip("\n")


def block(example: str, args: list[str]) -> str:
    cmd = "gatecost " + " ".join(args)
    return f"```console\n$ {cmd}\n{run(HERE / example, *args, '--root', '.')}\n```\n"


for d, top, variant, title, why in EXAMPLES:
    out = [f"# gatecost report: `{d}` ({title})\n",
           "Generated by `examples/make_reports.py` from the output of gatecost itself; nothing below is edited by hand.\n",
           why + "\n",
           "## Absolute cost\n",
           block(d, ["cost", "baseline", "--top", top, "--verbose"])]
    if variant:
        out += [f"## Modification: `baseline` -> `{variant}`\n",
                block(d, ["diff", "--before", "baseline", "--after", variant, "--top", top, "--verbose"])]
    out.append("The figures are analytic estimates, not synthesis results; see the limits in the top-level README.\n")
    (HERE / d / "REPORT.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote", d)
