#!/usr/bin/env python3
"""Regenerate REPORT.md from the actual output of gatecost (run from anywhere)."""
import os
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOL = HERE.parents[1] / "scripts" / "gatecost"
CACHE = tempfile.mkdtemp(prefix="gatecost-examples-")   # never write a cache next to the sources


def run(*args: str) -> str:
    p = subprocess.run([sys.executable, str(TOOL), *args], cwd=HERE, capture_output=True, text=True,
                       env=dict(os.environ, GATECOST_CACHE_DIR=CACHE))
    return p.stdout.rstrip("\n")


def block(title: str, args: list[str], lang: str = "text") -> str:
    cmd = "gatecost " + " ".join(f'"{a}"' if " " in a else a for a in args)
    return f"### {title}\n\n```console\n$ {cmd}\n{run(*args)}\n```\n"


common = ["--root", ".", "--top", "mac"]
out = [
    "# gatecost report: `mac` (multiply-accumulate unit)\n",
    "Generated by `make_report.py` from the output of gatecost itself; nothing below is edited by hand.\n",
    "The design is `acc <= acc + a*b` with asynchronous reset, synchronous clear and enable "
    "(8-bit operands, 24-bit accumulator), written in SystemVerilog and in VHDL.\n",
    "## 1. Absolute cost\n",
    block("SystemVerilog", ["cost", "baseline/sv", *common, "--verbose"]),
    block("VHDL", ["cost", "baseline/vhdl", *common, "--verbose"]),
    "## 2. Estimating a modification: register the product (pipeline stage)\n",
    "`pipelined/{sv,vhdl}` holds the same unit with the product `a*b` registered before the accumulation.\n",
    block("SystemVerilog", ["diff", "--before", "baseline/sv", "--after", "pipelined/sv", "--root", ".", "--top", "mac", "--verbose"]),
    block("VHDL", ["diff", "--before", "baseline/vhdl", "--after", "pipelined/vhdl", "--root", ".", "--top", "mac", "--verbose"]),
    "### Pull-request comment format (`--format markdown`, SystemVerilog)\n",
    run("diff", "--before", "baseline/sv", "--after", "pipelined/sv", "--root", ".", "--top", "mac", "--format", "markdown").replace("### ", "#### ", 1) + "\n",
    "## 3. Estimating before writing code\n",
    block("Cost of the datapath alone", ["estimate", "mul 8x8 + add 24"]),
    block("Cost of the accumulator register", ["estimate", "reg 24 async_reset sync_reset enable"]),
    block("From an RTL fragment", ["estimate", "--rtl", "assign p = a*b;", "--widths", "a=8,b=8"]),
    "## How to read this\n",
    "- `GE` is a 2-input NAND equivalent. The parentheses are the plausible range, not a statistical interval.\n"
    "- Confidence `low` or a verdict `UNCERTAIN` means the range is wider than the estimate or straddles zero: "
    "the sign of the change is not established. Use real synthesis for sign-off.\n"
    "- The figures are analytic estimates. The default profile is calibrated on one point only (Yosys + Nangate 45 nm, no timing constraint; see `docs/COST_MODEL.md` section 5.3), so they say little about a commercial flow or another node.\n",
]
(HERE / "REPORT.md").write_text("\n".join(out), encoding="utf-8")
print("wrote", HERE / "REPORT.md")
