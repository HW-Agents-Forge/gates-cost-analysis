"""Cost tree data model (SPEC.md section 5.5): the contract between the cost-tree builder
(`cost/build.py`), the differ (`diff/`) and the reporters.

design -> module (one per (module, parameter set, constant-port set)) -> operation.
All costs are integer milli-GE, PER INSTANCE of the module; the design total is
sum(op.cost.typ over a module's ops) * instance_count over every module (plus black boxes,
which are operations with category "blackbox"). Savings from sharing/fusion/folding are
assigned to the surviving operation, so the total is exactly the sum of operation costs.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from ..result import Diagnostic, Ge3


@dataclass(slots=True, frozen=True)
class CostOp:
    id: int                      # unique inside its module
    op: str                      # ADD, MUL, MUX, DFF, MEM, BLACKBOX, ...
    category: str                # seq addcmp mul select logic shift div mem blackbox
    quality: str                 # good | medium | poor
    cost: Ge3                    # per module instance, milli-GE
    sigma: int                   # independent residual uncertainty (milli-GE), COST_MODEL 5.1
    file: str
    line: int
    column: int = 0
    def_file: str | None = None  # macro definition site, when generated by a macro
    def_line: int | None = None
    named_key: tuple = ()        # IR.md section 7
    shape_key: str = ""          # hex Merkle hash
    declared_widths: tuple[int, ...] = ()
    effective_widths: tuple[int, ...] = ()
    tags: tuple[str, ...] = ()   # shared fused const_folded macro ...
    breakdown: dict = field(default_factory=dict)   # primitive -> count
    arch: dict = field(default_factory=dict)        # {"min","typ","max"} architecture names
    facts: dict = field(default_factory=dict)       # provenance: parameters, constants, widths, enable, ...
    description: str = ""        # fixed template, e.g. "MUL 16x16"
    members: tuple[int, ...] = ()  # ids of fused/shared member ops (attribution only; cost lives here)


@dataclass(slots=True, frozen=True)
class InstanceEdge:
    path: str                    # hierarchical instance name inside the parent, e.g. "u_alu" or "gen[3].u_mul"
    child_key: str               # key of the child ModuleCost
    count: int = 1               # array size


@dataclass(slots=True, frozen=True)
class ModuleCost:
    key: str                     # "name{P=1,Q=2}#ports" unique per elaboration
    name: str
    parameters: tuple[tuple[str, str], ...] = ()
    canonical_hash: str = ""     # IR.md section 7; equal hash => identical cost tree
    ops: tuple[CostOp, ...] = ()
    instances: tuple[InstanceEdge, ...] = ()
    diagnostics: tuple[Diagnostic, ...] = ()
    file: str = ""
    line: int = 0


@dataclass(slots=True, frozen=True)
class DesignCostTree:
    top_key: str
    modules: dict[str, ModuleCost]
    instance_counts: dict[str, int]          # key -> number of instances in the whole design
    diagnostics: tuple[Diagnostic, ...] = ()
    assumptions: tuple[str, ...] = ()
    config: dict = field(default_factory=dict)   # {"profile","defines","top"} for CONFIG_MISMATCH
    unsupported_in: frozenset[str] = frozenset() # module keys containing unsupported constructs

    def total(self) -> Ge3:
        mn = ty = mx = 0
        for k, m in self.modules.items():
            n = self.instance_counts.get(k, 0)
            for o in m.ops:
                mn += o.cost.min * n
                ty += o.cost.typ * n
                mx += o.cost.max * n
        return Ge3(mn, ty, mx)
